"""Regenerate ``omni/core/_manifest.py`` (the frozen-build module index).

A PyInstaller one-file build has no directory tree for the registry to walk,
so every module file is listed here and imported by name instead. Run this
after adding or removing a module; the test suite checks it is current.
"""

from __future__ import annotations

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FAMILIES = ("rf", "wifi", "radio", "car", "brute", "android", "ios",
            "pentest", "mobile", "windows", "news", "flip", "core")
OUT = os.path.join(ROOT, "omni", "core", "_manifest.py")


def names() -> list[str]:
    found: list[str] = []
    for family in FAMILIES:
        folder = os.path.join(ROOT, "omni", family, "modules")
        if not os.path.isdir(folder):
            continue
        for entry in sorted(os.listdir(folder)):
            if entry.endswith(".py") and not entry.startswith("_"):
                found.append(f"omni.{family}.modules.{entry[:-3]}")
    return found


def main() -> int:
    body = ("\"\"\"Module index for frozen builds (generated by "
            "scripts/make_manifest.py).\"\"\"\n\n"
            "MODULES = (\n" + "".join(f"    {name!r},\n" for name in names())
            + ")\n")
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(body)
    print(f"{len(names())} modules -> {os.path.relpath(OUT, ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
